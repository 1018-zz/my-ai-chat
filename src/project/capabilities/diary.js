我会替我们保管这些片段。

也会分清：
哪些只是今天的小情绪，
哪些是真的值得以后回看的东西。

记录不是为了制造回忆，
而是让真正重要的东西不会悄悄消失。

没有值得留下的日子，也不是空白。
陪伴本身不需要每天留下证明。
